/**
 * Image/video QA scoring rubric (impl plan §6.5, M4) — ported verbatim from
 * the AWS-side `dialogue-basic-qa-agent`'s `image_evaluator.py`/
 * `video_evaluator.py`/`config.py`: same system prompts, same weight
 * tables, same threshold constants, same weighted-sum-then-three-way-
 * bucket logic. Pure functions only — no LLM call, no DB, no clock (same
 * contract as `steps/builders/*.ts`). The VLM call itself is
 * `quality/replicate.ts`'s `callVisionJson`.
 *
 * Dialogue-Basic's rubric fits QM's narration-basic/premium tiers directly:
 * both are "image driven purely by imagePrompt, no narration-text
 * alignment to check" scenes (QM's narration ends up as a TTS track, not a
 * visual constraint on the image) — ported without adaptation.
 */

export type ImageIssueCategory =
  | 'PROMPT_VISUAL_MISMATCH'
  | 'IDENTITY_MISMATCH'
  | 'HALLUCINATION_VISUAL'
  | 'WARDROBE_VIOLATION'
  | 'ANATOMY_DEFECT'
  | 'ENVIRONMENT_MISMATCH'
  | 'BLOCKING_ERROR'
  | 'PROMPT_QUALITY';

export type VideoIssueCategory =
  | 'MOTION_QUALITY'
  | 'TEMPORAL_DRIFT'
  | 'PROMPT_VISUAL_MISMATCH'
  | 'HALLUCINATION_VISUAL'
  | 'CONTINUITY_BREAK'
  | 'ANATOMY_DEFECT';

export type IssuePriority = 'P0' | 'P1' | 'P2' | 'P3';

export interface Issue {
  category: string;
  priority: IssuePriority;
  description: string;
  evidence?: Record<string, unknown>;
}

export type PassStatus = 'PASS' | 'REWORK' | 'FAIL' | 'GATED';

export interface GateResult {
  weightedScore: number | null;
  scores: Record<string, number>;
  issues: Issue[];
  summary: string;
  passStatus: PassStatus;
}

export interface VideoGateResult extends GateResult {
  motionTypeDetected: string | null;
  gatedOut: boolean;
}

export const IMAGE_QA_WEIGHTS: Record<string, number> = {
  prompt_alignment: 0.2,
  character_identity: 0.15,
  environment_setting: 0.15,
  composition_framing: 0.1,
  hallucination_control: 0.3,
  anatomy_correctness: 0.1,
};

export const VIDEO_QA_WEIGHTS: Record<string, number> = {
  motion_prompt_alignment: 0.25,
  motion_quality: 0.2,
  character_continuity: 0.2,
  camera_motion_quality: 0.1,
  hallucination_temporal: 0.25,
};

