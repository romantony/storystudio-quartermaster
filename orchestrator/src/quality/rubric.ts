function weightedSum(scores: Record<string, number>, weights: Record<string, number>): number {
  let sum = 0;
  for (const [dim, weight] of Object.entries(weights)) {
    sum += (scores[dim] ?? 0) * weight;
  }
  return Math.round(sum * 100) / 100;
}

export interface ImageGateThresholds {
  passThreshold: number;
  reviewThreshold: number;
}

/** Buckets a raw VLM JSON response into the {weightedScore, scores, issues,
 * summary, passStatus} shape. Does not call the VLM — pure function over an
 * already-parsed response, matching image_evaluator.py's post-call logic. */
export function scoreImage(vlmResult: { scores?: Record<string, number>; issues?: Issue[]; summary?: string }, thresholds: ImageGateThresholds): GateResult {
  const scores = vlmResult.scores ?? {};
  const weightedScore = weightedSum(scores, IMAGE_QA_WEIGHTS);
  const passStatus: PassStatus =
    weightedScore >= thresholds.passThreshold ? 'PASS' : weightedScore >= thresholds.reviewThreshold ? 'REWORK' : 'FAIL';
  return { weightedScore, scores, issues: vlmResult.issues ?? [], summary: vlmResult.summary ?? '', passStatus };
}

export function imageEvalFailedResult(reason: string): GateResult {
  return {
    weightedScore: 0,
    scores: {},
    issues: [{ category: 'PROMPT_QUALITY', priority: 'P0', description: reason, evidence: {} }],
    summary: 'Evaluation failed',
    passStatus: 'FAIL',
  };
}

export interface VideoGateThresholds {
  gateThreshold: number;
  passThreshold: number;
  reviewThreshold: number;
}

/** Mirrors video_evaluator.py's gate-by-image-score pre-check — skip the
 * (costly) video VLM call entirely when the source image already scored
 * too low to plausibly pass, since the animator inherits the source
 * frame's defects rather than fixing them. */
export function isVideoGatedByImageScore(imageQaScore: number, thresholds: VideoGateThresholds): boolean {
  return imageQaScore < thresholds.gateThreshold;
}

export function videoGatedResult(imageQaScore: number, thresholds: VideoGateThresholds): VideoGateResult {
  return {
    weightedScore: null,
    scores: {},
    issues: [],
    motionTypeDetected: null,
    summary: `Video QA skipped — image score ${imageQaScore.toFixed(2)} < gate threshold ${thresholds.gateThreshold}`,
    passStatus: 'GATED',
    gatedOut: true,
  };
}

export function scoreVideo(
  vlmResult: { scores?: Record<string, number>; motion_type_detected?: string; issues?: Issue[]; summary?: string },
  thresholds: VideoGateThresholds,
): VideoGateResult {
  const scores = vlmResult.scores ?? {};
  const weightedScore = weightedSum(scores, VIDEO_QA_WEIGHTS);
  const passStatus: PassStatus =
    weightedScore >= thresholds.passThreshold ? 'PASS' : weightedScore >= thresholds.reviewThreshold ? 'REWORK' : 'FAIL';
  return {
    weightedScore,
    scores,
    issues: vlmResult.issues ?? [],
    motionTypeDetected: vlmResult.motion_type_detected ?? null,
    summary: vlmResult.summary ?? '',
    passStatus,
    gatedOut: false,
  };
}

export function videoEvalFailedResult(reason: string): VideoGateResult {
  return {
    weightedScore: 0,
    scores: {},
    issues: [{ category: 'MOTION_QUALITY', priority: 'P0', description: reason, evidence: {} }],
    motionTypeDetected: null,
    summary: 'Evaluation failed',
    passStatus: 'FAIL',
    gatedOut: false,
  };
}
